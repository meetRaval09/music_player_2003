const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  close: () => ipcRenderer.send('w:close'),
  min: () => ipcRenderer.send('w:min'),
  fit: (h) => ipcRenderer.send('w:fit', h),
  playing: (on) => ipcRenderer.send('w:playing', !!on),
  pin: () => ipcRenderer.invoke('w:pin'),
  getPin: () => ipcRenderer.invoke('w:getPin'),
  buddyState: (s) => ipcRenderer.send('buddy:state', s),
  spotifyOn: () => ipcRenderer.send('spotify:on'),
  spotifyOff: () => ipcRenderer.send('spotify:off'),
  spotifyCmd: (n) => ipcRenderer.send('spotify:cmd', n),
  onSpotify: (cb) => ipcRenderer.on('spotify:state', (_e, s) => cb(s)),
  spStatus: () => ipcRenderer.invoke('sp:status'),
  spSetClient: (id) => ipcRenderer.invoke('sp:setClient', id),
  spLogin: () => ipcRenderer.invoke('sp:login'),
  spLogout: () => ipcRenderer.invoke('sp:logout'),
  spReset: () => ipcRenderer.invoke('sp:reset'),
  spPlaylists: () => ipcRenderer.invoke('sp:playlists'),
  spItems: (id) => ipcRenderer.invoke('sp:items', id),
  spPlay: (ctx, track, uris) => ipcRenderer.invoke('sp:play', ctx, track, uris),
  spSearch: (q, off) => ipcRenderer.invoke('sp:search', q, off),
  onBuddyCmd: (cb) => ipcRenderer.on('buddy:cmd', (_e, name) => cb(name)),
});
